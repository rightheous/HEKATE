from __future__ import annotations

from collections.abc import Sequence
from typing import Protocol

from hekate.domain.models import (
    Account, AccountSnapshot, AdmissionReceipt, AdmissionRequest, AgentRecord, AuditEvent,
    Attempt, AuthorizationSnapshot, BillableCallIntent, BudgetReservation,
    CallObservation, CallPermit, EvidenceRecord, ExecutionObservation, InboxReceipt,
    Lease, Operation, OperationClaim, OutboxJob, Page, PositionVersionRecord,
    PublicEvent, Reservation, ReservationRequest, SettlementReceipt, StoredConclusion,
    Task, UsageObservation, UsageReceipt,
)
from hekate.domain.types import (
    AccountingCallId, AttemptId, EvidenceId, OperationId, PermitId, PrincipalId,
    ProviderAgentId, RegistryId, ScopeId, TaskId, TopicId,
)
from collections.abc import Mapping


class TaskRepository(Protocol):
    async def insert_scope(self, snapshot: AuthorizationSnapshot) -> None: ...
    async def lock_scope(self, scope: ScopeId) -> AuthorizationSnapshot: ...
    async def claim_submission(self, scope: ScopeId, request_key: str, request_hash: str) -> Mapping[str, object]: ...
    async def complete_submission(self, scope: ScopeId, request_key: str, task_id: TaskId, receipt: Mapping[str, object]) -> None: ...
    async def insert_task(self, task: Task, constraints: Mapping[str, object] | None = None) -> None: ...
    async def lock_task(self, task_id: TaskId) -> Task: ...
    async def get_task_input(self, task_id: TaskId, revision: int) -> Mapping[str, object] | None: ...
    async def get_attempt(self, attempt_id: AttemptId, for_update: bool = False) -> Attempt: ...
    async def attempt_exists(self, attempt_id: AttemptId) -> bool: ...
    async def insert_attempt(self, attempt: Attempt) -> None: ...
    async def apply_admission(self, task: Task, attempt_kind: str) -> None: ...
    async def revise_input(self, task_id: TaskId, expected_revision: int, change: object, constraints_hash: str, **kwargs: object) -> Task: ...
    async def request_cancel(self, task_id: TaskId, reason: object) -> Task: ...
    async def increment_provider_calls(self, task_id: TaskId) -> None: ...
    async def compare_and_set_state(self, task_id: TaskId, expected: object, update: object) -> bool: ...
    async def increment_counter_if_below(self, task_id: TaskId, counter: str, cap: int) -> bool: ...
    async def list_queued(self, limit: int = 20) -> Sequence[Mapping[str, object]]: ...
    async def claim_task_preparation(self, task_id: TaskId, revision: int, operation_id: str, attempt_id: str, reservation_id: str, owner: str, ttl_seconds: int) -> Mapping[str, object]: ...
    async def mark_task_preparation_admitted(self, task_id: TaskId, revision: int, owner: str, conversation_id: str, fence: int) -> None: ...
    async def release_task_preparation(self, task_id: TaskId, revision: int, owner: str) -> None: ...
    async def fail_expired_queued(self, now: object) -> int: ...
    async def fail_queued_task(self, task_id: TaskId, reason: object) -> bool: ...
    async def get_task_response(self, task_id: TaskId) -> Mapping[str, object] | None: ...
    async def get_task_cost_status(self, task_id: TaskId) -> Mapping[str, object]: ...
    async def finalize_task_response(self, task_id: TaskId, revision: int, response: Mapping[str, object], *, successful: bool) -> bool: ...
    async def resolve_task_after_execution(self, task_id: TaskId, revision: int) -> Task | None: ...
    async def list_execution_terminal_candidates(self, limit: int = 100) -> Sequence[Mapping[str, object]]: ...
    async def list_pending_turn_results(self, limit: int = 100) -> Sequence[str]: ...


class AgentRepository(Protocol):
    async def get_persistent_owner(self, owner: PrincipalId) -> AgentRecord | None: ...
    async def get_persistent_scope(self, owner_scope: ScopeId, *, lock: bool = False) -> AgentRecord | None: ...
    async def insert_intent(self, record: AgentRecord) -> None: ...
    async def bind_provider(self, registry_id: RegistryId, provider_id: ProviderAgentId) -> None: ...
    async def update_observation(self, registry_id: RegistryId, observation: object) -> None: ...
    async def acquire_lease(self, registry_id: RegistryId, owner: str, ttl: float) -> Lease | None: ...
    async def renew_lease(self, lease: Lease) -> Lease: ...
    async def release_lease(self, lease: Lease) -> None: ...
    async def lock_registry(self, registry_id: RegistryId) -> AgentRecord: ...
    async def assert_current_lease(self, registry_id: RegistryId, owner: str, fence: int) -> Lease: ...
    async def get_lease(self, registry_id: RegistryId) -> Lease | None: ...
    async def active_execution_hold(self, registry_id: RegistryId, *, lock: bool = False) -> object: ...
    async def create_execution_hold(self, registry_id: RegistryId, operation_id: OperationId) -> None: ...
    async def set_registry_busy(self, registry_id: RegistryId, attempt_id: str) -> None: ...
    async def set_registry_ready(self, registry_id: RegistryId) -> None: ...


class BudgetRepository(Protocol):
    async def lock_accounts(self, account_ids: Sequence[str]) -> Sequence[Account]: ...
    async def create_account(self, account: AccountSnapshot) -> None: ...
    async def ensure_account(self, account: AccountSnapshot) -> None: ...
    async def reserve_operation(self, request: ReservationRequest) -> BudgetReservation: ...
    async def get_reservation(self, reservation_id: ReservationId, *, lock: bool = False) -> Mapping[str, object] | None: ...
    async def allocate_call(self, intent: BillableCallIntent, reservation_id: object, attempt_id: AttemptId, envelope: object, intent_hash: str) -> CallPermit: ...
    async def get_call_descriptor(self, accounting_call_id: AccountingCallId) -> Mapping[str, object] | None: ...
    async def get_call(self, accounting_call_id: AccountingCallId, *, lock: bool = False) -> Mapping[str, object] | None: ...
    async def count_calls_by_kind(self, operation_id: OperationId, call_kind: str) -> int: ...
    async def lock_call_accounts(self, accounting_call_id: AccountingCallId) -> Sequence[Account]: ...
    async def consume_call_permit(self, permit_id: PermitId, accounting_call_id: AccountingCallId) -> CallPermit: ...
    async def record_call_observation(self, observation: CallObservation) -> None: ...
    async def record_usage(self, observation: UsageObservation) -> UsageReceipt: ...
    async def settle_call(self, accounting_call_id: AccountingCallId) -> SettlementReceipt: ...
    async def call_ids_for_operation(self, operation_id: OperationId) -> Sequence[str]: ...
    async def call_ids_for_reservation(self, reservation_id: ReservationId) -> Sequence[str]: ...
    async def release_unallocated_after_quiescence(self, operation_id: OperationId) -> None: ...
    async def apply_adjustment(self, account_id: str, effect_key: str, amount: object, **kwargs: object) -> bool: ...
    async def list_pending_calls(self, limit: int = 100) -> Sequence[Mapping[str, object]]: ...


