class DeliveryRepository(Protocol):
    async def claim_lifecycle_operation(self, operation_id: OperationId, owner_scope: ScopeId, kind: str, request_hash: str) -> Mapping[str, object]: ...
    async def claim_operation(self, operation_id: OperationId, owner_scope: ScopeId, task_id: TaskId, kind: str, request_hash: str, binding: Mapping[str, object], envelope: Mapping[str, object]) -> OperationClaim: ...
    async def lock_operation(self, operation_id: OperationId, request_hash: str | None = None) -> Mapping[str, object]: ...
    async def lock_task_operations(self, task_id: TaskId) -> Sequence[Mapping[str, object]]: ...
    async def task_execution_states(self, task_id: TaskId) -> Sequence[Mapping[str, object]]: ...
    async def complete_admission(self, receipt: AdmissionReceipt) -> None: ...
    async def store_commit_receipt(self, operation_id: OperationId, request_hash: str, receipt: object) -> None: ...
    async def update_operation(self, operation_id: OperationId, expected: object, observation: object) -> None: ...
    async def append_outbox(self, job: OutboxJob) -> None: ...
    async def claim_jobs(self, worker: str, limit: int, lease: float) -> Sequence[OutboxJob]: ...
    async def get_dispatch_payload(self, operation_id: OperationId) -> Mapping[str, object] | None: ...
    async def record_send_intent(self, job: OutboxJob, worker: str, fence: int) -> None: ...
    async def mark_dispatch_accepted(self, job: OutboxJob, worker: str, fence: int) -> None: ...
    async def ack_job(self, job: OutboxJob, worker: str, fence: int) -> None: ...
    async def reschedule_job(self, job: OutboxJob, worker: str, fence: int, error: str, delay: float) -> None: ...
    async def insert_inbox_once(self, provider_scope: str, stable_event_key: str, payload: Mapping[str, object], payload_hash: str) -> InboxReceipt: ...
    async def lock_inbox(self, inbox_id: str) -> Mapping[str, object] | None: ...
    async def mark_inbox_processed(self, inbox_id: str) -> None: ...
    async def defer_inbox(self, inbox_id: str, reason: str, delay: float = 1.0) -> None: ...
    async def reject_inbox(self, inbox_id: str, reason: str) -> None: ...
    async def pending_inbox(self, limit: int = 100) -> Sequence[Mapping[str, object]]: ...
    async def pending_terminal_inbox(self, operation_id: OperationId) -> Sequence[Mapping[str, object]]: ...
    async def record_execution(self, observation: ExecutionObservation) -> None: ...
    async def append_audit(self, event: AuditEvent) -> None: ...
    async def read_public_events(self, task_id: TaskId, after: object) -> Page[PublicEvent]: ...


class UnitOfWork(Protocol):
    tasks: TaskRepository
    agents: AgentRepository
    budgets: BudgetRepository
    knowledge: KnowledgeRepository
    delivery: DeliveryRepository

    async def __aenter__(self) -> UnitOfWork: ...
    async def __aexit__(self, exc_type: object, exc: object, traceback: object) -> None: ...
    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...


class UowFactory(Protocol):
    def __call__(self) -> UnitOfWork: ...
