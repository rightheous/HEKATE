    async def update_turn_result(self, inbox_id: str, *, state: str, proposal: object = None, conclusion_id: str | None = None, rejection_reason: str | None = None, delay_seconds: float = 0) -> None: ...
    async def get_conclusion(self, conclusion_id: str) -> Mapping[str, object] | None: ...
    async def set_conclusion_eligible(self, conclusion_id: str, eligible: bool, reason: str | None) -> None: ...
